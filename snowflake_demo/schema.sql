CREATE STAGE IF NOT EXISTS RESERVING_FILES;

CREATE FILE FORMAT IF NOT EXISTS RESERVING_CSV
  TYPE = CSV SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"';

CREATE TABLE IF NOT EXISTS RESERVING_IMPORTS (
    IMPORT_ID VARCHAR NOT NULL,
    IMPORTED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
    DATASET VARCHAR NOT NULL,
    STAGE_FILE VARCHAR NOT NULL,
    FILE_SHA256 VARCHAR NOT NULL,
    INPUT_SHA256 VARCHAR NOT NULL,
    INPUT_CSV VARCHAR NOT NULL,
    OBSERVATIONS ARRAY NOT NULL
);

CREATE TABLE IF NOT EXISTS RESERVING_ATTEMPTS (
    ATTEMPT_ID VARCHAR NOT NULL,
    IMPORT_ID VARCHAR NOT NULL,
    PLATFORM_QUERY_ID VARCHAR,
    TASK_RUN_GROUP_ID VARCHAR,
    PAYLOAD VARIANT NOT NULL,
    VALIDATION VARIANT NOT NULL,
    DIAGNOSTICS VARIANT NOT NULL,
    ARTIFACTS VARIANT NOT NULL
);

CREATE OR REPLACE VIEW RESERVING_TRIANGLES COPY GRANTS AS
SELECT s.IMPORT_ID, s.IMPORTED_AT, s.DATASET, s.INPUT_SHA256,
       obs.value[0]::INTEGER AS ORIGIN, obs.value[1]::INTEGER AS DEVELOPMENT,
       obs.value[2]::DOUBLE AS CLAIM_VALUE
FROM RESERVING_IMPORTS AS s, LATERAL FLATTEN(INPUT => s.OBSERVATIONS) AS obs;

CREATE OR REPLACE VIEW RESERVING_WARNINGS COPY GRANTS AS
SELECT a.ATTEMPT_ID, 'validation' AS CHECK_STAGE, c.value:check_id::VARCHAR AS CHECK_ID,
       c.value:verdict::VARCHAR AS VERDICT, c.value:details AS DETAILS
FROM RESERVING_ATTEMPTS AS a, LATERAL FLATTEN(INPUT => a.VALIDATION:checks) AS c
WHERE c.value:verdict::VARCHAR IN ('warn', 'fail')
UNION ALL
SELECT a.ATTEMPT_ID, 'diagnostics', c.value:test_id::VARCHAR,
       c.value:verdict::VARCHAR, c.value
FROM RESERVING_ATTEMPTS AS a, LATERAL FLATTEN(INPUT => a.DIAGNOSTICS:tests) AS c
WHERE c.value:verdict::VARCHAR IN ('warn', 'fail');

CREATE OR REPLACE VIEW RESERVING_RUNS COPY GRANTS AS
SELECT a.ATTEMPT_ID, a.IMPORT_ID, a.PLATFORM_QUERY_ID, a.TASK_RUN_GROUP_ID,
       a.PAYLOAD:started_at::TIMESTAMP_TZ AS STARTED_AT,
       a.PAYLOAD:dataset::VARCHAR AS DATASET, a.PAYLOAD:method::VARCHAR AS METHOD,
       a.PAYLOAD:status::VARCHAR AS STATUS, STRIP_NULL_VALUE(a.PAYLOAD:model_run_id)::VARCHAR AS MODEL_RUN_ID,
       a.PAYLOAD:input_sha256::VARCHAR AS INPUT_SHA256,
       a.PAYLOAD:harness_version::VARCHAR AS HARNESS_VERSION,
       a.PAYLOAD:bundle_sha256::VARCHAR AS BUNDLE_SHA256,
       STRIP_NULL_VALUE(a.PAYLOAD:validation_verdict)::VARCHAR AS VALIDATION_VERDICT,
       STRIP_NULL_VALUE(a.PAYLOAD:diagnostics_verdict)::VARCHAR AS DIAGNOSTICS_VERDICT,
       STRIP_NULL_VALUE(a.PAYLOAD:latest)::DOUBLE AS LATEST, STRIP_NULL_VALUE(a.PAYLOAD:ultimate)::DOUBLE AS ULTIMATE,
       STRIP_NULL_VALUE(a.PAYLOAD:ibnr)::DOUBLE AS IBNR, STRIP_NULL_VALUE(a.PAYLOAD:mack_se)::DOUBLE AS MACK_SE,
       w.DETAILS:origin::VARCHAR::INTEGER AS NEGATIVE_ORIGIN,
       w.DETAILS:dev::INTEGER AS NEGATIVE_DEVELOPMENT_AGE,
       w.DETAILS:incremental::DOUBLE AS NEGATIVE_INCREMENTAL,
       GET(a.ARTIFACTS, 'model/report.html') IS NOT NULL AS REPORT_AVAILABLE
FROM RESERVING_ATTEMPTS AS a
LEFT JOIN RESERVING_WARNINGS AS w
    ON w.ATTEMPT_ID = a.ATTEMPT_ID AND w.CHECK_STAGE = 'validation'
    AND w.CHECK_ID = 'nonneg_incrementals';

CREATE OR REPLACE VIEW RESERVING_REPORTS COPY GRANTS AS
SELECT ATTEMPT_ID, GET(ARTIFACTS, 'model/report.html')::VARCHAR AS REPORT_HTML
FROM RESERVING_ATTEMPTS
WHERE GET(ARTIFACTS, 'model/report.html') IS NOT NULL;
